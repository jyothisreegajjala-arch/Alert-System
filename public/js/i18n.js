  // Get currently selected language code
  getLanguage: () => {
    const saved = localStorage.getItem('careconnect_language');
    if (saved && CareConnectI18n.translations[saved]) {
      return saved;
    }
    // Auto-detect from browser settings (Requirement 2)
    const navLang = (navigator.language || navigator.userLanguage || 'en').substring(0, 2);
    if (CareConnectI18n.translations[navLang]) {
      return navLang;
    }
    return 'en'; // Default fallback
  },

  // Set language preference
  setLanguage: (langCode) => {
    if (!CareConnectI18n.translations[langCode]) return;
    localStorage.setItem('careconnect_language', langCode);
    
    // Set HTML dir for RTL languages (Urdu)
    const langObj = CareConnectI18n.supportedLanguages.find(l => l.code === langCode);
    if (langObj && langObj.dir === 'rtl') {
      document.documentElement.setAttribute('dir', 'rtl');
    } else {
      document.documentElement.setAttribute('dir', 'ltr');
    }
    document.documentElement.setAttribute('lang', langCode);

    CareConnectI18n.updateDOM();

    // Trigger custom event for reactive modules
    window.dispatchEvent(new CustomEvent('careconnect_language_changed', { detail: { language: langCode } }));
  },

  // Get translated string by key
  t: (key) => {
    const lang = CareConnectI18n.getLanguage();
    const dict = CareConnectI18n.translations[lang] || CareConnectI18n.translations.en;
    return dict[key] || CareConnectI18n.translations.en[key] || key;
  },

  // Dynamic DOM Translator (Requirement 4)
  updateDOM: () => {
    const lang = CareConnectI18n.getLanguage();
    const dict = CareConnectI18n.translations[lang] || CareConnectI18n.translations.en;

    // Translate all text elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // Translate all placeholders with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // Update active state in language triggers
    const activeLangObj = CareConnectI18n.supportedLanguages.find(l => l.code === lang) || CareConnectI18n.supportedLanguages[0];
    document.querySelectorAll('.lang-trigger-label').forEach(el => {
      el.textContent = activeLangObj.native;
    });
    document.querySelectorAll('.lang-trigger-flag').forEach(el => {
      el.textContent = activeLangObj.flag;
    });
  },

