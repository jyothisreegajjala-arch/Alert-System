  // Get current language from localStorage or fallback to browser default
  getLanguage: () => {
    const saved = localStorage.getItem('careconnect_lang');
    if (saved && CareConnectI18n.translations[saved]) {
      return saved;
    }
    const navLang = (navigator.language || 'en').split('-')[0];
    return CareConnectI18n.translations[navLang] ? navLang : 'en';
  },

  // Set active language and trigger instant DOM translation across the application
  setLanguage: (langCode) => {
    if (!CareConnectI18n.translations[langCode]) {
      langCode = 'en';
    }
    localStorage.setItem('careconnect_lang', langCode);
    document.documentElement.lang = langCode;

    // Apply RTL for Urdu
    const activeLangObj = CareConnectI18n.supportedLanguages.find(l => l.code === langCode);
    if (activeLangObj && activeLangObj.dir === 'rtl') {
      document.documentElement.setAttribute('dir', 'rtl');
    } else {
      document.documentElement.removeAttribute('dir');
    }

    CareConnectI18n.updateDOM();

    // Trigger custom event for reactive modules (Admin Dashboard, Tables, Stats)
    window.dispatchEvent(new CustomEvent('careconnect_language_changed', { detail: { language: langCode } }));
  },

  // Get translated string by key
  t: (key) => {
    const lang = CareConnectI18n.getLanguage();
    const dict = CareConnectI18n.translations[lang] || CareConnectI18n.translations.en;
    return dict[key] || CareConnectI18n.translations.en[key] || key;
  },

  // Dynamic DOM Translator (Translates all data-i18n, placeholders, and fallback nodes)
  updateDOM: () => {
    const lang = CareConnectI18n.getLanguage();
    const dict = CareConnectI18n.translations[lang] || CareConnectI18n.translations.en;

    // 1. Translate all elements with explicit data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // 2. Translate all placeholders with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // 3. Update active state in language triggers
    const activeLangObj = CareConnectI18n.supportedLanguages.find(l => l.code === lang) || CareConnectI18n.supportedLanguages[0];
    document.querySelectorAll('.lang-trigger-label').forEach(el => {
      el.textContent = activeLangObj.native;
    });
    document.querySelectorAll('.lang-trigger-flag').forEach(el => {
      el.textContent = activeLangObj.flag;
    });
  },

  // Toggle custom line-by-line language popover dropdown
  toggleDropdown: (triggerBtn) => {
    const wrapper = triggerBtn.closest('.language-selector-wrapper');
    if (!wrapper) return;
    const popover = wrapper.querySelector('.lang-popover-menu');
    if (!popover) return;

    const isHidden = popover.classList.contains('d-none');
    
    // Close any other open language popovers
    document.querySelectorAll('.lang-popover-menu').forEach(menu => menu.classList.add('d-none'));

    if (isHidden) {
      popover.classList.remove('d-none');
      popover.style.left = '';
      popover.style.right = '0';
      const rect = popover.getBoundingClientRect();
      if (rect.left < 10) {
        popover.style.left = '0';
        popover.style.right = 'auto';
      }
      const rect2 = popover.getBoundingClientRect();
      if (rect2.right > window.innerWidth - 10) {
        popover.style.right = '0';
        popover.style.left = 'auto';
      }
    }
  },

